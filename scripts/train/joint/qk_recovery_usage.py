def expected_private_names():
    return {emb:sorted(name for name,scope in ALL_PARAMETER_SCOPES.items() if scope==emb) for emb in EMBODIMENTS}



def expected_parameters():
    result={}
    banks=[('image_model','shared',True),('proprio_banks.eva_bimanual','eva_bimanual',False),
           ('proprio_banks.human_bimanual','human_bimanual',False),('action','eva_bimanual',False),('camera','shared',False)]
    for bank,scope,image in banks:
        for layer in range(8):
            base=PREFIX+bank+'.blocks.'+str(layer)+'.'
            for suffix in ('gate_value.weight','gate_value.bias','output.weight','output.bias'):
                result[base+'ffn.'+('0.' if image else '')+suffix]=scope
            for kind in ('q_norm','k_norm'):
                result[base+kind+'.'+('0.' if image else '')+'weight']=scope
    for emb in EMBODIMENTS:
        for direction in ('inputs','outputs'):
            for kind in ('weight','bias'):result[PREFIX+'camera.'+direction+'.'+emb+'.'+kind]=emb
    return result


def private_scope(name):
    for emb in EMBODIMENTS:
        if name.startswith((PREFIX+'proprio_banks.'+emb+'.',PREFIX+'language_fusions.proprio__'+emb+'.')) or any(name.startswith(PREFIX+'camera.'+d+'.'+emb+'.') for d in ('inputs','outputs')):
            return emb
    if name.startswith((PREFIX+'action.',PREFIX+'language_fusions.action.')):return 'eva_bimanual'
    return None


def snapshot_private(module,optimizer):
    # Called only inside actual allocated diagnostic, after strict restoration.
    from scripts.train.joint.native_recovery import state_digest
    named=list(module.named_parameters())
    need(len(named)==len(ALL_PARAMETER_SCOPES) and {name for name,_ in named}==set(ALL_PARAMETER_SCOPES),'Wrong exact558 private-snapshot parameter inventory')
    state={emb:{} for emb in EMBODIMENTS}
    for name,parameter in named:
        emb=private_scope(name)
        if emb:state[emb][name]={'weight':parameter.detach(),'optimizer':optimizer.state.get(parameter,{})}
    need(all(state.values()),'Both private optimizer banks must exist')
    return {emb:state_digest(values) for emb,values in state.items()}


def verify_row(row):
    batches=row['embodiment_optimizer_batches'];initial=row['initial_parameter_usage']
    final=row['conditional_optimizer_record']['parameter_update_counts'];expected=expected_all_parameters()
    names=row['conditional_optimizer_record']['parameter_names']
    need(isinstance(names,list) and len(names)==len(set(names))==len(expected),'Wrong exact558 ordered parameter inventory')
    need(set(batches)==set(EMBODIMENTS) and all(type(v) is int and v>=0 for v in batches.values()),'Wrong actual embodiment batch counts')
    count=row['global_step']-row['start_step']
    need(count in (2,4) and sum(batches.values())==count and set(expected)==set(initial)==set(final)==set(row['conditional_optimizer_record']['parameter_names']),'Missing exact new parameter inventory')
    actual_new={n for n in final if any(x in n for x in ('.q_norm.','.k_norm.','.ffn.gate_value.','.ffn.output.','.ffn.0.gate_value.','.ffn.0.output.'))}
    need(actual_new=={n for n in expected_parameters() if not any(x in n for x in ('.camera.inputs.','.camera.outputs.'))},'QK/SwiGLU names/banks differ')
    for name,scope in expected.items():
        updates=count if scope=='shared' else batches[scope]
        need(type(initial[name]) is type(final[name]) is int and final[name]-initial[name]==updates,
             'QK/SwiGLU actual gradient/Adam usage differs: '+name)
    proof=row['qk_private_state']
    need(proof.get('schema')=='qk-private-state-preservation-v2' and proof.get('parameter_names')==expected_private_names() and set(proof['before'])==set(proof['after'])==set(EMBODIMENTS),
         'Actual private-state snapshots missing')
    for emb in EMBODIMENTS:
        need(all(isinstance(proof[k][emb],str) and re.fullmatch('[0-9a-f]{64}',proof[k][emb]) for k in ('before','after')),
             'Malformed private-state digest')
        if batches[emb]==0:need(proof['before'][emb]==proof['after'][emb],'Inactive private weights/Adam state changed')
    return True


def verify_phases(phases):
    need(len(phases)==2 and all(len(rows)==4 for rows in phases),'QK diagnostic needs actual two processes/four ranks')
    for rows in phases:
        for row in rows:verify_row(row)
        need(all(row['qk_private_state']==rows[0]['qk_private_state'] for row in rows),'Private states differ across ranks')
    for first,second in zip(*phases):
        need(first['qk_private_state']['after']==second['qk_private_state']['before'],'Second process did not restore private state exactly')
    return dict(qk_swiglu_conditional_updates_verified=True,inactive_private_weights_and_adam_preserved=True,
                qk_parameter_tensors=80,swiglu_parameter_tensors=160,all_conditional_parameter_tensors=558,private_language_fusion_parameter_tensors=12,sampling_unchanged=True)
