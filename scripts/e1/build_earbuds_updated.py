"""Freeze the rl2 wireless_earbuds_updated pool into a manifest and data config.

Read-only SQL. Refuses while any row of the task is still unconverted, so the
split is never cut around episodes that are about to land (--allow-pending
overrides). Validation is ceil(5%) of usable episodes, allocated to operators
by largest remainder (ties in casefolded operator order); each operator's
sorted IDs are shuffled by random.Random(42) and the first k go to validation.

    python scripts/e1/build_earbuds_updated.py [--allow-pending]
"""

import argparse
import contextlib
import json
import math
import os
import random
import sys
from datetime import datetime, timezone
from pathlib import Path

from egomimic.rldb.zarr.zarr_dataset_multi import episode_names_sha256

TASK = "wireless_earbuds_updated"
ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "scripts/e1/earbuds_updated_manifest.json"
DATA = ROOT / "egomimic/hydra_configs/data/abc_arc/earbuds_updated.yaml"
LAMBDA = (
    f"lambda row: row['lab'] == 'rl2' and row['task'] == '{TASK}' and row['embodiment'] == 'yam_bimanual'"
    " and not row['is_deleted'] and not row['is_eval'] and row['num_frames'] > 0"
    " and bool(row['zarr_processed_path']) and not row['zarr_processing_error']"
)


usable = eval(LAMBDA)


def query():
    for key in ("AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "AWS_SESSION_TOKEN", "AWS_SECURITY_TOKEN"):
        os.environ.pop(key, None)
    from sqlalchemy import select, text

    from egomimic.utils.aws.aws_sql import _episodes_table, create_default_engine

    with contextlib.redirect_stdout(sys.stderr):
        engine = create_default_engine()
        table = _episodes_table(engine)
    with engine.connect() as connection:
        connection.execute(text("SET TRANSACTION READ ONLY"))
        stmt = select(table).where((table.c.lab == "rl2") & (table.c.task == TASK))
        return [dict(r) for r in connection.execute(stmt).mappings()]


def split(episodes, seed=42):
    by_op = {}
    for e in episodes:
        by_op.setdefault(e["operator"], []).append(e["episode_hash"])
    n_val = math.ceil(0.05 * len(episodes))
    ops = sorted(by_op, key=str.casefold)
    quota = {op: n_val * len(by_op[op]) / len(episodes) for op in ops}
    counts = {op: math.floor(q) for op, q in quota.items()}
    for op in sorted(ops, key=lambda o: -(quota[o] - counts[o]))[: n_val - sum(counts.values())]:
        counts[op] += 1
    valid = []
    for op in ops:
        ids = sorted(by_op[op])
        random.Random(seed).shuffle(ids)
        valid += ids[: counts[op]]
    train = sorted({e["episode_hash"] for e in episodes} - set(valid))
    return train, sorted(valid), counts


def yaml_role(hashes):
    lines = "".join(f"      - '{h}'\n" for h in hashes)
    return (
        f"    filters:\n      filter_lambdas:\n      - \"{LAMBDA}\"\n      episode_hashes:\n{lines}"
        f"    expected_train_episode_count: {len(hashes)}\n"
        f"    expected_train_episode_names_sha256: {episode_names_sha256(hashes)}\n"
        f"    expected_valid_episode_count: 0\n"
        f"    expected_valid_episode_names_sha256: {episode_names_sha256([])}\n"
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--allow-pending", action="store_true")
    args = ap.parse_args()
    rows = query()
    episodes = sorted((r for r in rows if usable(r)), key=lambda r: r["episode_hash"])
    pending = [r["episode_hash"] for r in rows if not usable(r) and not r["is_deleted"] and not r["is_eval"]]
    print(f"{TASK}: {len(rows)} rows, {len(episodes)} usable, {len(pending)} pending", file=sys.stderr)
    if pending and not args.allow_pending:
        sys.exit(f"REFUSING: {len(pending)} rows not converted yet: {pending}")
    train, valid, counts = split(episodes)
    assert not set(train) & set(valid) and len(train) + len(valid) == len(episodes)
    keep = ("episode_hash", "operator", "num_frames", "zarr_processed_path", "task")
    MANIFEST.write_text(json.dumps({
        "queried_at_utc": datetime.now(timezone.utc).isoformat(),
        "task": TASK,
        "split_seed": 42,
        "validation_rule": __doc__.split("\n\n")[1].replace("\n", " "),
        "validation_operator_counts": counts,
        "pending_excluded": pending,
        "pools": {"all": {"train": train, "valid": valid}},
        "episodes": [{k: e[k] for k in keep} for e in episodes],
    }, indent=1) + "\n")
    DATA.write_text(
        f"# Generated by scripts/e1/build_earbuds_updated.py; frozen membership, do not hand-edit.\n"
        f"defaults:\n- /data/abc_arc/towels_hpt300@_here_\n- _self_\n"
        f"train_datasets:\n  yam_bimanual:\n{yaml_role(train)}"
        f"valid_datasets:\n  yam_bimanual:\n{yaml_role(valid)}"
    )
    frames = sum(e["num_frames"] for e in episodes)
    print(json.dumps({"episodes": len(episodes), "frames": frames, "train": len(train), "valid": len(valid),
                      "valid_by_operator": counts, "pending": len(pending)}))


if __name__ == "__main__":
    main()
